import Foundation

public struct AIToolsCleaner: CleanerProvider {
    public let category: CleanerCategory
    private let home: String
    private let executor: CleanupExecutor
    private let planner: CleanupPlanner

    public init(
        category: CleanerCategory,
        homeDirectory: String = FileManager.default.homeDirectoryForCurrentUser.path,
        executor: CleanupExecutor? = nil
    ) {
        self.category = category
        self.home = homeDirectory
        let validator = SafetyValidator(homeDirectory: homeDirectory)
        self.executor = executor ?? CleanupExecutor(validator: validator)
        self.planner = CleanupPlanner(validator: validator)
    }

    public func scan(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) async -> [CleanableItem] {
        switch category {
        case .claude:
            return scanClaude(snapshot: snapshot, ageFilter: ageFilter)
        case .codex:
            return scanCodex(snapshot: snapshot, ageFilter: ageFilter)
        case .googleAI:
            return scanGoogleAI(snapshot: snapshot, ageFilter: ageFilter)
        default:
            return []
        }
    }

    private func scanClaude(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .claude)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        let claudeRoot = "\(home)/Library/Application Support/Claude"
        guard FileManager.default.fileExists(atPath: claudeRoot) else { return [] }

        var excludedFromSessions = Set<String>()

        let targets: [(id: String, name: String, subpath: String, risk: RiskLevel, supportsAge: Bool, redownload: Bool, explanation: String, regen: String)] = [
            (
                "claude-cache",
                "Claude Cache",
                "Cache",
                .safe,
                true,
                false,
                "Temporary HTTP and application cache inside ~/Library/Application Support/Claude/Cache.",
                "Automatically regenerated when Claude runs. Does not affect sessions or configuration."
            ),
            (
                "claude-code-cache",
                "Claude Code Cache",
                "Code Cache",
                .safe,
                true,
                false,
                "Compiled JS bytecode cache inside ~/Library/Application Support/Claude/Code Cache.",
                "Automatically regenerated when Claude runs. Does not affect sessions or configuration."
            ),
            (
                "claude-gpu-cache",
                "Claude GPU Cache",
                "GPUCache",
                .safe,
                true,
                false,
                "Shader and GPU pipeline cache inside ~/Library/Application Support/Claude/GPUCache.",
                "Automatically regenerated when Claude runs. Does not affect sessions or configuration."
            ),
            (
                "claude-dawn-webgpu-cache",
                "Claude Dawn WebGPU Cache",
                "DawnWebGPUCache",
                .safe,
                true,
                false,
                "Temporary Dawn WebGPU pipeline cache inside ~/Library/Application Support/Claude/DawnWebGPUCache.",
                "Automatically regenerated when Claude renders GPU views."
            ),
            (
                "claude-dawn-graphite-cache",
                "Claude Dawn Graphite Cache",
                "DawnGraphiteCache",
                .safe,
                true,
                false,
                "Temporary Dawn Graphite cache inside ~/Library/Application Support/Claude/DawnGraphiteCache.",
                "Automatically regenerated when Claude runs."
            ),
            (
                "claude-simulator-builds",
                "Claude Simulator Builds (simulator-builds)",
                "simulator-builds",
                .review,
                false,
                false,
                "Cached simulator build bundles and DerivedData generated by Claude / Claude iOS Sim. These files can be regenerated, but Claude may need to rebuild or download them again.",
                "These files can be regenerated, but Claude may need to rebuild or download them again. Does not affect chat sessions or credentials."
            ),
            (
                "claude-vm-bundles",
                "Claude VM Bundles (vm_bundles)",
                "vm_bundles",
                .review,
                false,
                true,
                "Virtual machine bundle images (rootfs.img / vmlinuz) used by Claude local execution environment. These files can be regenerated, but Claude may need to rebuild or download them again.",
                "These files can be regenerated, but Claude may need to rebuild or download them again (~10 GB VM image)."
            )
        ]

        for t in targets {
            let fullPath = "\(claudeRoot)/\(t.subpath)"
            guard FileManager.default.fileExists(atPath: fullPath) else { continue }
            let standardized = URL(fileURLWithPath: fullPath).standardizedFileURL.path
            excludedFromSessions.insert(standardized)

            let usage = DiskScanner.shared.measurePath(fullPath)
            guard usage.physicalSize > 0 else { continue }

            let minDays = (t.supportsAge && ageFilter != .all) ? ageFilter.rawValue : nil
            let plan = planner.planDirectoryContents(
                directoryPath: fullPath,
                baseRisk: t.risk,
                ageFilter: ageFilter,
                supportsAgeFilter: t.supportsAge,
                isRunningDependency: false
            )

            items.append(
                CleanableItem(
                    id: t.id,
                    name: t.name,
                    category: .claude,
                    path: fullPath,
                    logicalSize: usage.logicalSize,
                    physicalSize: usage.physicalSize,
                    reclaimableSize: plan.eligibleBytes,
                    lastModified: plan.latestModified ?? usage.lastModified,
                    riskLevel: t.risk,
                    explanation: t.explanation,
                    deletionConsequence: "Moves eligible contents of \(t.subpath) to macOS Trash. Blocked if Claude or Claude iOS Sim is running.",
                    regenerationImpact: t.regen,
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .moveToTrashContents(directoryPath: fullPath, minAgeDays: minDays),
                    supportsAgeFilter: t.supportsAge,
                    plan: plan,
                    requiresRedownload: t.redownload,
                    affectsSessionsOrConfig: false
                )
            )
        }

        // Inspect ~/Library/Application Support/Claude/claude-code for old vs active tool versions
        let claudeCodeDir = "\(claudeRoot)/claude-code"
        if FileManager.default.fileExists(atPath: claudeCodeDir) {
            let standardizedCC = URL(fileURLWithPath: claudeCodeDir).standardizedFileURL.path
            excludedFromSessions.insert(standardizedCC)

            let sdkVersionPath = "\(claudeRoot)/claude-code-vm/.sdk-version"
            let configuredVersion = (try? String(contentsOfFile: sdkVersionPath, encoding: .utf8))?
                .trimmingCharacters(in: .whitespacesAndNewlines)

            let versionDirs = ((try? FileManager.default.contentsOfDirectory(
                at: URL(fileURLWithPath: claudeCodeDir),
                includingPropertiesForKeys: [.isDirectoryKey, .isSymbolicLinkKey],
                options: [.skipsHiddenFiles]
            )) ?? []).filter { url in
                let vals = try? url.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
                return vals?.isDirectory == true && vals?.isSymbolicLink != true
            }.sorted { lhs, rhs in
                lhs.lastPathComponent.compare(rhs.lastPathComponent, options: .numeric) == .orderedAscending
            }

            let activeVersionName = configuredVersion ?? versionDirs.last?.lastPathComponent

            for vURL in versionDirs {
                let vName = vURL.lastPathComponent
                let vPath = vURL.standardizedFileURL.path
                let usage = DiskScanner.shared.measurePath(vPath)
                guard usage.physicalSize > 0 else { continue }

                if vName == activeVersionName {
                    items.append(
                        CleanableItem(
                            id: "claude-code-active-\(vName)",
                            name: "Claude Code Active Tool Version (v\(vName))",
                            category: .claude,
                            path: vPath,
                            logicalSize: usage.logicalSize,
                            physicalSize: usage.physicalSize,
                            reclaimableSize: 0,
                            lastModified: usage.lastModified,
                            riskLevel: .neverDelete,
                            explanation: "Currently active Claude Code CLI/VM binary version (v\(vName)).",
                            deletionConsequence: "Protected: Active tool binary version is never deleted.",
                            regenerationImpact: "Required by current Claude Code environment.",
                            isRunningDependency: isRunning,
                            runningProcessNames: runningProcs,
                            actionType: .readOnlyInfo(reason: "Active Claude Code version v\(vName) is protected."),
                            requiresRedownload: true,
                            affectsSessionsOrConfig: false
                        )
                    )
                } else {
                    items.append(
                        CleanableItem(
                            id: "claude-code-old-\(vName)",
                            name: "Claude Code Superseded Version (v\(vName))",
                            category: .claude,
                            path: vPath,
                            logicalSize: usage.logicalSize,
                            physicalSize: usage.physicalSize,
                            reclaimableSize: usage.physicalSize,
                            lastModified: usage.lastModified,
                            riskLevel: .review,
                            explanation: "Older Claude Code binary installation (v\(vName)), superseded by v\(activeVersionName ?? "latest").",
                            deletionConsequence: "Moves superseded Claude Code v\(vName) binary folder to macOS Trash without affecting sessions or active v\(activeVersionName ?? "latest").",
                            regenerationImpact: "Only re-downloaded if an older SDK version is explicitly requested.",
                            isRunningDependency: isRunning,
                            runningProcessNames: runningProcs,
                            actionType: .moveToTrash(path: vPath),
                            requiresRedownload: true,
                            affectsSessionsOrConfig: false
                        )
                    )
                }
            }
        }

        let sessionsUsage = DiskScanner.shared.measurePath(claudeRoot, excludedSubpaths: excludedFromSessions)

        items.append(
            CleanableItem(
                id: "claude-sessions-config-keep",
                name: "Claude Sessions & Configuration",
                category: .claude,
                path: claudeRoot,
                logicalSize: sessionsUsage.logicalSize,
                physicalSize: sessionsUsage.physicalSize,
                reclaimableSize: 0,
                lastModified: sessionsUsage.lastModified,
                riskLevel: .neverDelete,
                explanation: "Claude sessions (local-agent-mode-sessions, claude-code-sessions), side-session-notes, MCP configuration, local storage, cookies, and workspace state.",
                deletionConsequence: "Protected: Never deleted automatically.",
                regenerationImpact: "Contains user session state, conversation history, credentials, and configuration.",
                isRunningDependency: isRunning,
                runningProcessNames: runningProcs,
                actionType: .readOnlyInfo(reason: "Claude sessions and configuration are strictly protected."),
                requiresRedownload: false,
                affectsSessionsOrConfig: true
            )
        )

        return items
    }

    private func scanCodex(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .codex)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        // 1. ~/.cache/codex-runtimes (REVIEW)
        let runtimesPath = "\(home)/.cache/codex-runtimes"
        if FileManager.default.fileExists(atPath: runtimesPath) {
            let usage = DiskScanner.shared.measurePath(runtimesPath)
            if usage.physicalSize > 0 {
                let plan = planner.planDirectoryContents(
                    directoryPath: runtimesPath,
                    baseRisk: .review,
                    ageFilter: ageFilter,
                    supportsAgeFilter: false,
                    isRunningDependency: false
                )
                let stagedInstallCount = plan.eligibleEntries.filter { $0.name.hasPrefix("codex-runtime-install-") }.count
                let stagedDetail = stagedInstallCount > 0
                    ? " Includes codex-primary-runtime and \(stagedInstallCount) staged/old codex-runtime-install-* directories."
                    : ""
                items.append(
                    CleanableItem(
                        id: "codex-runtimes-cache",
                        name: "Codex Runtimes (~/.cache/codex-runtimes)",
                        category: .codex,
                        path: runtimesPath,
                        logicalSize: usage.logicalSize,
                        physicalSize: usage.physicalSize,
                        reclaimableSize: plan.eligibleBytes,
                        lastModified: plan.latestModified ?? usage.lastModified,
                        riskLevel: .review,
                        explanation: "Cached runtime installations in ~/.cache/codex-runtimes.\(stagedDetail)",
                        deletionConsequence: "Moves cached Codex runtime installations to macOS Trash while keeping Codex app configuration and sessions intact.",
                        regenerationImpact: "Active Codex runtime may need to be unpacked or downloaded again on next launch.",
                        isRunningDependency: isRunning,
                        runningProcessNames: runningProcs,
                        actionType: .moveToTrashContents(directoryPath: runtimesPath, minAgeDays: nil),
                        plan: plan,
                        requiresRedownload: true,
                        affectsSessionsOrConfig: false
                    )
                )
            }
        }

        // 2. ~/Library/Caches/Codex (SAFE)
        let cachesCodex = "\(home)/Library/Caches/Codex"
        if FileManager.default.fileExists(atPath: cachesCodex) {
            let usage = DiskScanner.shared.measurePath(cachesCodex)
            if usage.physicalSize > 0 {
                let minDays = ageFilter != .all ? ageFilter.rawValue : nil
                let plan = planner.planDirectoryContents(
                    directoryPath: cachesCodex,
                    baseRisk: .safe,
                    ageFilter: ageFilter,
                    supportsAgeFilter: true,
                    isRunningDependency: false
                )
                items.append(
                    CleanableItem(
                        id: "codex-library-cache",
                        name: "Codex Cache (~/Library/Caches/Codex)",
                        category: .codex,
                        path: cachesCodex,
                        logicalSize: usage.logicalSize,
                        physicalSize: usage.physicalSize,
                        reclaimableSize: plan.eligibleBytes,
                        lastModified: plan.latestModified ?? usage.lastModified,
                        riskLevel: .safe,
                        explanation: "Standard macOS cache directory for Codex.",
                        deletionConsequence: "Moves eligible temporary cache files in ~/Library/Caches/Codex to macOS Trash.",
                        regenerationImpact: "Automatically regenerated by Codex. Does not affect sessions or configuration.",
                        isRunningDependency: isRunning,
                        runningProcessNames: runningProcs,
                        actionType: .moveToTrashContents(directoryPath: cachesCodex, minAgeDays: minDays),
                        supportsAgeFilter: true,
                        plan: plan,
                        requiresRedownload: false,
                        affectsSessionsOrConfig: false
                    )
                )
            }
        }

        // 3. ~/Library/Application Support/Codex (Keep session/config, allow only Cache/Code Cache/GPUCache/Dawn* as SAFE)
        let appSupportCodex = "\(home)/Library/Application Support/Codex"
        if FileManager.default.fileExists(atPath: appSupportCodex) {
            var excludedFromCodexSessions = Set<String>()
            let minDays = ageFilter != .all ? ageFilter.rawValue : nil
            for sub in ["Cache", "Code Cache", "GPUCache", "DawnWebGPUCache", "DawnGraphiteCache"] {
                let p = "\(appSupportCodex)/\(sub)"
                if FileManager.default.fileExists(atPath: p) {
                    excludedFromCodexSessions.insert(URL(fileURLWithPath: p).standardizedFileURL.path)
                    let u = DiskScanner.shared.measurePath(p)
                    if u.physicalSize > 0 {
                        let plan = planner.planDirectoryContents(
                            directoryPath: p,
                            baseRisk: .safe,
                            ageFilter: ageFilter,
                            supportsAgeFilter: true,
                            isRunningDependency: false
                        )
                        items.append(
                            CleanableItem(
                                id: "codex-appsupport-\(sub.lowercased().replacingOccurrences(of: " ", with: "-"))",
                                name: "Codex \(sub)",
                                category: .codex,
                                path: p,
                                logicalSize: u.logicalSize,
                                physicalSize: u.physicalSize,
                                reclaimableSize: plan.eligibleBytes,
                                lastModified: plan.latestModified ?? u.lastModified,
                                riskLevel: .safe,
                                explanation: "Temporary \(sub) inside ~/Library/Application Support/Codex/\(sub).",
                                deletionConsequence: "Moves eligible temporary cache files to macOS Trash without touching Codex sessions or settings.",
                                regenerationImpact: "Automatically regenerated. Does not affect sessions or configuration.",
                                isRunningDependency: isRunning,
                                runningProcessNames: runningProcs,
                                actionType: .moveToTrashContents(directoryPath: p, minAgeDays: minDays),
                                supportsAgeFilter: true,
                                plan: plan,
                                requiresRedownload: false,
                                affectsSessionsOrConfig: false
                            )
                        )
                    }
                }
            }

            let codexSessionsUsage = DiskScanner.shared.measurePath(
                appSupportCodex,
                excludedSubpaths: excludedFromCodexSessions
            )

            items.append(
                CleanableItem(
                    id: "codex-sessions-keep",
                    name: "Codex Sessions & Configuration",
                    category: .codex,
                    path: appSupportCodex,
                    logicalSize: codexSessionsUsage.logicalSize,
                    physicalSize: codexSessionsUsage.physicalSize,
                    reclaimableSize: 0,
                    lastModified: codexSessionsUsage.lastModified,
                    riskLevel: .neverDelete,
                    explanation: "Codex artifact-sessions, account/session state, cookies, and preferences.",
                    deletionConsequence: "Protected: Never deleted.",
                    regenerationImpact: "Preserves your Codex login, sessions, and configuration.",
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .readOnlyInfo(reason: "Codex configuration and session data are preserved."),
                    requiresRedownload: false,
                    affectsSessionsOrConfig: true
                )
            )
        }

        return items
    }

    private func scanGoogleAI(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .googleAI)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        let base = "\(home)/Library/Application Support/com.google.AIEdgeForesight"
        guard FileManager.default.fileExists(atPath: base) else { return [] }

        let subdirs: [(id: String, name: String, sub: String)] = [
            ("google-ai-models", "AIEdgeForesight Local Models (models)", "models"),
            ("google-ai-model-cache", "AIEdgeForesight Model Cache (model_cache)", "model_cache")
        ]

        for s in subdirs {
            let fullPath = "\(base)/\(s.sub)"
            guard FileManager.default.fileExists(atPath: fullPath) else { continue }
            let usage = DiskScanner.shared.measurePath(fullPath)
            guard usage.physicalSize > 0 else { continue }

            let plan = planner.planDirectoryContents(
                directoryPath: fullPath,
                baseRisk: .review,
                ageFilter: ageFilter,
                supportsAgeFilter: false,
                isRunningDependency: false
            )

            items.append(
                CleanableItem(
                    id: s.id,
                    name: s.name,
                    category: .googleAI,
                    path: fullPath,
                    logicalSize: usage.logicalSize,
                    physicalSize: usage.physicalSize,
                    reclaimableSize: plan.eligibleBytes,
                    lastModified: plan.latestModified ?? usage.lastModified,
                    riskLevel: .review,
                    explanation: "Local Google AI model weights and compiled model caches (\(s.sub)). Removing local AI models can recover significant storage but may trigger a large download or model rebuild later.",
                    deletionConsequence: "Moves cached local AI model weights to macOS Trash. Never auto-selected in Recommended Cleanup.",
                    regenerationImpact: "Removing local AI models can recover significant storage but may trigger a large download or model rebuild later.",
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .moveToTrashContents(directoryPath: fullPath, minAgeDays: nil),
                    plan: plan,
                    requiresRedownload: true,
                    affectsSessionsOrConfig: false
                )
            )
        }

        return items
    }

    public func clean(_ item: CleanableItem, ageFilter: AgeFilter) async throws -> CleanupResult {
        try await executor.execute(item, ageFilter: ageFilter)
    }
}
