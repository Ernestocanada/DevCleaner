import Foundation

public struct AIToolsCleaner: CleanerProvider {
    public let category: CleanerCategory
    private let home: String
    private let executor: CleanupExecutor

    public init(
        category: CleanerCategory,
        homeDirectory: String = FileManager.default.homeDirectoryForCurrentUser.path,
        executor: CleanupExecutor = CleanupExecutor()
    ) {
        self.category = category
        self.home = homeDirectory
        self.executor = executor
    }

    public func scan(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) async -> [CleanableItem] {
        switch category {
        case .claude:
            return scanClaude(snapshot: snapshot, ageFilter: ageFilter)
        case .codex:
            return scanCodex(snapshot: snapshot, ageFilter: ageFilter)
        case .googleAI:
            return scanGoogleAI(snapshot: snapshot, ageFilter: ageFilter)
        default:
            return []
        }
    }

    private func scanClaude(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .claude)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        let claudeRoot = "\(home)/Library/Application Support/Claude"
        guard FileManager.default.fileExists(atPath: claudeRoot) else { return [] }

        let targets: [(id: String, name: String, subpath: String, risk: RiskLevel, explanation: String, regen: String)] = [
            (
                "claude-cache",
                "Claude Cache",
                "Cache",
                .safe,
                "Temporary HTTP and application cache inside ~/Library/Application Support/Claude/Cache.",
                "Automatically regenerated when Claude runs."
            ),
            (
                "claude-code-cache",
                "Claude Code Cache",
                "Code Cache",
                .safe,
                "Compiled JS bytecode cache inside ~/Library/Application Support/Claude/Code Cache.",
                "Automatically regenerated when Claude runs."
            ),
            (
                "claude-gpu-cache",
                "Claude GPU Cache",
                "GPUCache",
                .safe,
                "Shader and GPU pipeline cache inside ~/Library/Application Support/Claude/GPUCache.",
                "Automatically regenerated when Claude runs."
            ),
            (
                "claude-simulator-builds",
                "Claude Simulator Builds (simulator-builds)",
                "simulator-builds",
                .review,
                "Cached simulator build bundles generated by Claude / Claude iOS Sim. These files can be regenerated, but Claude may need to rebuild or download them again.",
                "These files can be regenerated, but Claude may need to rebuild or download them again."
            ),
            (
                "claude-vm-bundles",
                "Claude VM Bundles (vm_bundles)",
                "vm_bundles",
                .review,
                "Virtual machine bundle images used by Claude local execution environment. These files can be regenerated, but Claude may need to rebuild or download them again.",
                "These files can be regenerated, but Claude may need to rebuild or download them again."
            )
        ]

        for t in targets {
            let fullPath = "\(claudeRoot)/\(t.subpath)"
            guard FileManager.default.fileExists(atPath: fullPath) else { continue }
            let usage = DiskScanner.shared.measurePath(fullPath)
            guard usage.physicalSize > 0 else { continue }

            items.append(
                CleanableItem(
                    id: t.id,
                    name: t.name,
                    category: .claude,
                    path: fullPath,
                    logicalSize: usage.logicalSize,
                    physicalSize: usage.physicalSize,
                    reclaimableSize: usage.physicalSize,
                    lastModified: usage.lastModified,
                    riskLevel: t.risk,
                    explanation: t.explanation,
                    deletionConsequence: "Moves contents of \(t.subpath) to macOS Trash. Blocked if Claude or Claude iOS Sim is running.",
                    regenerationImpact: t.regen,
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .moveToTrashContents(directoryPath: fullPath, minAgeDays: nil)
                )
            )
        }

        // Explicitly list Claude Sessions & Configuration as NEVER DELETE
        items.append(
            CleanableItem(
                id: "claude-sessions-config-keep",
                name: "Claude Sessions & Configuration",
                category: .claude,
                path: claudeRoot,
                logicalSize: 0,
                physicalSize: 0,
                reclaimableSize: 0,
                lastModified: nil,
                riskLevel: .neverDelete,
                explanation: "Claude sessions, side-session-notes, MCP configuration, local storage, cookies, and workspace state.",
                deletionConsequence: "Protected: Never deleted automatically.",
                regenerationImpact: "Contains user session state and configuration.",
                isRunningDependency: isRunning,
                runningProcessNames: runningProcs,
                actionType: .readOnlyInfo(reason: "Claude sessions and configuration are strictly protected.")
            )
        )

        return items
    }

    private func scanCodex(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .codex)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        // 1. ~/.cache/codex-runtimes (REVIEW)
        let runtimesPath = "\(home)/.cache/codex-runtimes"
        if FileManager.default.fileExists(atPath: runtimesPath) {
            let usage = DiskScanner.shared.measurePath(runtimesPath)
            if usage.physicalSize > 0 {
                items.append(
                    CleanableItem(
                        id: "codex-runtimes-cache",
                        name: "Codex Runtimes (~/.cache/codex-runtimes)",
                        category: .codex,
                        path: runtimesPath,
                        logicalSize: usage.logicalSize,
                        physicalSize: usage.physicalSize,
                        reclaimableSize: usage.physicalSize,
                        lastModified: usage.lastModified,
                        riskLevel: .review,
                        explanation: "Cached runtime installations in ~/.cache/codex-runtimes.",
                        deletionConsequence: "Moves cached Codex runtime installations to macOS Trash while keeping Codex app configuration.",
                        regenerationImpact: "Active Codex runtime may need to be unpacked or downloaded again on next launch.",
                        isRunningDependency: isRunning,
                        runningProcessNames: runningProcs,
                        actionType: .moveToTrashContents(directoryPath: runtimesPath, minAgeDays: nil)
                    )
                )
            }
        }

        // 2. ~/Library/Caches/Codex (SAFE)
        let cachesCodex = "\(home)/Library/Caches/Codex"
        if FileManager.default.fileExists(atPath: cachesCodex) {
            let usage = DiskScanner.shared.measurePath(cachesCodex)
            if usage.physicalSize > 0 {
                items.append(
                    CleanableItem(
                        id: "codex-library-cache",
                        name: "Codex Cache (~/Library/Caches/Codex)",
                        category: .codex,
                        path: cachesCodex,
                        logicalSize: usage.logicalSize,
                        physicalSize: usage.physicalSize,
                        reclaimableSize: usage.physicalSize,
                        lastModified: usage.lastModified,
                        riskLevel: .safe,
                        explanation: "Standard macOS cache directory for Codex.",
                        deletionConsequence: "Moves temporary cache files in ~/Library/Caches/Codex to macOS Trash.",
                        regenerationImpact: "Automatically regenerated by Codex.",
                        isRunningDependency: isRunning,
                        runningProcessNames: runningProcs,
                        actionType: .moveToTrashContents(directoryPath: cachesCodex, minAgeDays: nil),
                        supportsAgeFilter: true
                    )
                )
            }
        }

        // 3. ~/Library/Application Support/Codex (Keep session/config, allow only Cache/Code Cache/GPUCache as SAFE)
        let appSupportCodex = "\(home)/Library/Application Support/Codex"
        if FileManager.default.fileExists(atPath: appSupportCodex) {
            for sub in ["Cache", "Code Cache", "GPUCache"] {
                let p = "\(appSupportCodex)/\(sub)"
                if FileManager.default.fileExists(atPath: p) {
                    let u = DiskScanner.shared.measurePath(p)
                    if u.physicalSize > 0 {
                        items.append(
                            CleanableItem(
                                id: "codex-appsupport-\(sub.lowercased().replacingOccurrences(of: " ", with: "-"))",
                                name: "Codex \(sub)",
                                category: .codex,
                                path: p,
                                logicalSize: u.logicalSize,
                                physicalSize: u.physicalSize,
                                reclaimableSize: u.physicalSize,
                                lastModified: u.lastModified,
                                riskLevel: .safe,
                                explanation: "Temporary \(sub) inside ~/Library/Application Support/Codex/\(sub).",
                                deletionConsequence: "Moves temporary cache files to macOS Trash without touching Codex sessions or settings.",
                                regenerationImpact: "Automatically regenerated.",
                                isRunningDependency: isRunning,
                                runningProcessNames: runningProcs,
                                actionType: .moveToTrashContents(directoryPath: p, minAgeDays: nil)
                            )
                        )
                    }
                }
            }

            items.append(
                CleanableItem(
                    id: "codex-sessions-keep",
                    name: "Codex Sessions & Configuration",
                    category: .codex,
                    path: appSupportCodex,
                    logicalSize: 0,
                    physicalSize: 0,
                    reclaimableSize: 0,
                    lastModified: nil,
                    riskLevel: .neverDelete,
                    explanation: "Codex artifact-sessions, account/session state, cookies, and preferences.",
                    deletionConsequence: "Protected: Never deleted.",
                    regenerationImpact: "Preserves your Codex login, sessions, and configuration.",
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .readOnlyInfo(reason: "Codex configuration and session data are preserved.")
                )
            )
        }

        return items
    }

    private func scanGoogleAI(snapshot: ActiveProcessSnapshot, ageFilter: AgeFilter) -> [CleanableItem] {
        let runningProcs = snapshot.matchingProcesses(for: .googleAI)
        let isRunning = !runningProcs.isEmpty
        var items: [CleanableItem] = []

        let base = "\(home)/Library/Application Support/com.google.AIEdgeForesight"
        guard FileManager.default.fileExists(atPath: base) else { return [] }

        let subdirs: [(id: String, name: String, sub: String)] = [
            ("google-ai-models", "AIEdgeForesight Local Models (models)", "models"),
            ("google-ai-model-cache", "AIEdgeForesight Model Cache (model_cache)", "model_cache")
        ]

        for s in subdirs {
            let fullPath = "\(base)/\(s.sub)"
            guard FileManager.default.fileExists(atPath: fullPath) else { continue }
            let usage = DiskScanner.shared.measurePath(fullPath)
            guard usage.physicalSize > 0 else { continue }

            items.append(
                CleanableItem(
                    id: s.id,
                    name: s.name,
                    category: .googleAI,
                    path: fullPath,
                    logicalSize: usage.logicalSize,
                    physicalSize: usage.physicalSize,
                    reclaimableSize: usage.physicalSize,
                    lastModified: usage.lastModified,
                    riskLevel: .review,
                    explanation: "Local Google AI model weights and compiled model caches (\(s.sub)). Removing local AI models can recover significant storage but may trigger a large download or model rebuild later.",
                    deletionConsequence: "Moves cached local AI model weights to macOS Trash. Never auto-selected in Recommended Cleanup.",
                    regenerationImpact: "Removing local AI models can recover significant storage but may trigger a large download or model rebuild later.",
                    isRunningDependency: isRunning,
                    runningProcessNames: runningProcs,
                    actionType: .moveToTrashContents(directoryPath: fullPath, minAgeDays: nil)
                )
            )
        }

        return items
    }

    public func clean(_ item: CleanableItem, ageFilter: AgeFilter) async throws -> CleanupResult {
        try await executor.execute(item, ageFilter: ageFilter)
    }
}
